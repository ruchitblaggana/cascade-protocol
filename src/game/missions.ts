export function getMission(id: string): Mission | undefined {
  return MISSIONS.find(m => m.id === id);
}

export function getUnlockedMissions(completedMissionIds: string[]): { mission: Mission; unlocked: boolean }[] {
  return MISSIONS.map(m => ({
    mission: m,
    unlocked: m.unlockAfter === null || completedMissionIds.includes(m.unlockAfter),
  }));
}
